function indexCountries(): Readonly<Record<string, Region>> {
  const map: Record<string, Region> = {};
  for (const region of REGIONS) {
    for (const code of COUNTRIES[region]) {
      if (map[code]) throw new Error(`Duplicate country code ${code}`);
      map[code] = region;
    }
  }
  return map;
}

/** Static ISO alpha-2 map. Lookup is case-insensitive via `regionForCountry`. */
export const COUNTRY_REGIONS: Readonly<Record<string, Region>> =
  indexCountries();

/**
 * Region for an ISO alpha-2 code. `UK` is accepted as an alias of `GB`.
 * Missing and unrecognised codes return `Unknown`.
 */
export function regionForCountry(code: string | null | undefined): Region {
  if (code == null) return "Unknown";
  const normalised = code.trim().toUpperCase();
  if (normalised === "UK") return "UK";
  return COUNTRY_REGIONS[normalised] ?? "Unknown";
}

/** ISO alpha-2 codes in a region, sorted. Used by region filters. */
export function countriesInRegion(region: Region): readonly string[] {
  return COUNTRIES[region];
}
